package com.shnwaz.lyramusic.lyrics

import android.content.Context
import com.shnwaz.lyramusic.lrclib.LrcLib
import com.shnwaz.lyramusic.constants.EnableLrcLibKey
import com.shnwaz.lyramusic.utils.dataStore
import com.shnwaz.lyramusic.utils.get

object LrcLibLyricsProvider : LyricsProvider {
    override val name = "LrcLib"

    override fun isEnabled(context: Context): Boolean = context.dataStore[EnableLrcLibKey] ?: true

    override suspend fun getLyrics(
        id: String,
        title: String,
        artist: String,
        album: String?,
        duration: Int,
    ): Result<String> = LrcLib.getLyrics(title, artist, duration)

    override suspend fun getAllLyrics(
        id: String,
        title: String,
        artist: String,
        album: String?,
        duration: Int,
        callback: (String) -> Unit,
    ) {
        LrcLib.getAllLyrics(title, artist, duration, null, callback)
    }
}
